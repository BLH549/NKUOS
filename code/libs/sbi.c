/*
 * Lab1 的旧式 SBI 服务封装。编号 0～8 对应模板保留的固件服务。
 * 仅实现通用调用、字符输出与定时器设置；编号存在不代表对应包装函数已实现。
 */
// libs/sbi.c
/* 逐行：引入 SBI 包装接口声明，使 C 代码可以通过函数调用发起固件服务请求。 */
#include <sbi.h>
/* 逐行：引入 uint64_t、size_t、NULL 等内核基础类型和宏。 */
#include <defs.h>


/* 逐行：定义旧式定时器服务编号 0；这是 64 位可写全局变量，不是预处理器常量。 */
uint64_t SBI_SET_TIMER = 0;
/* 逐行：定义旧式字符输出服务编号 1，当前内核打印启动消息时使用它。 */
uint64_t SBI_CONSOLE_PUTCHAR = 1;
/* 逐行：定义旧式字符输入编号 2；编号存在不表示本仓库实现了输入包装函数。 */
uint64_t SBI_CONSOLE_GETCHAR = 2;
/* 逐行：保留旧式清除处理器间中断编号 3；当前启动路径不调用该服务。 */
uint64_t SBI_CLEAR_IPI = 3;
/* 逐行：保留旧式发送处理器间中断编号 4；Lab1 不通过它进行多核协作。 */
uint64_t SBI_SEND_IPI = 4;
/* 逐行：保留远程指令缓存同步服务编号 5，用于请求目标 hart 执行相应指令同步。 */
uint64_t SBI_REMOTE_FENCE_I = 5;
/* 逐行：保留远程地址转换同步服务编号 6，当前 Lab1 尚未使用页表同步功能。 */
uint64_t SBI_REMOTE_SFENCE_VMA = 6;
/* 逐行：保留带 ASID 的远程地址转换同步编号 7，服务可按地址空间标识限定同步范围。 */
uint64_t SBI_REMOTE_SFENCE_VMA_ASID = 7;
/* 逐行：保留旧式关机服务编号 8；当前 kern_init 末尾循环，没有发起关机请求。 */
uint64_t SBI_SHUTDOWN = 8;

/*
 * sbi_call：按本代码采用的旧式 SBI 约定发起固件服务请求。
 * 参数 sbi_type：服务编号；arg0、arg1、arg2：前三个服务参数。
 * 汇编依次把编号放入 x17/a7，把参数放入 x10/a0、x11/a1、x12/a2，
 * 通过 ecall 请求 M 模式的 OpenSBI，再读取 a0 作为 uint64_t 返回值。
 * volatile 保留汇编操作，memory 声明阻止编译器把内存访问随意跨越此块。
 * 这是现有内联汇编的约定说明，memory 不等同于硬件内存屏障。
 */
/* 逐行：进入通用 SBI 调用封装，接收服务编号与三个参数，返回固件交回的 64 位结果。 */
uint64_t sbi_call(uint64_t sbi_type, uint64_t arg0, uint64_t arg1, uint64_t arg2) {
    /* 逐行：预留 C 返回结果变量，由下面汇编的输出操作数写入后再返回。 */
    uint64_t ret_val;
    /* 逐行：开始 GCC 扩展内联汇编；volatile 表示这段汇编有必须保留的副作用。 */
    __asm__ volatile (
        /* 逐行：把命名输入 sbi_type 复制到 x17/a7，作为旧式 SBI 服务编号；换行分隔汇编指令。 */
        "mv x17, %[sbi_type]\n"
        /* 逐行：把第一个服务参数复制到 x10/a0；字符输出时这里保存要输出的字节值。 */
        "mv x10, %[arg0]\n"
        /* 逐行：把第二个服务参数复制到 x11/a1；当前字符输出包装传入零。 */
        "mv x11, %[arg1]\n"
        /* 逐行：把第三个服务参数复制到 x12/a2；当前字符输出包装传入零。 */
        "mv x12, %[arg2]\n"
        /* 逐行：执行环境调用并触发异常；在本实验配置中从 S 模式进入 M 模式 OpenSBI 服务处理。 */
        "ecall\n"
        /* 逐行：固件返回后，把 x10/a0 的结果复制到编译器为 ret_val 分配的输出寄存器。 */
        "mv %[ret_val], x10"
        /* 逐行：第一个冒号列输出操作数：ret_val 是命名占位符，= 表示只写，r 请求通用寄存器。 */
        : [ret_val] "=r" (ret_val)
        /* 逐行：第二个冒号列四个输入：命名占位符对应 C 值，r 让编译器先把各值放入寄存器。 */
        : [sbi_type] "r" (sbi_type), [arg0] "r" (arg0), [arg1] "r" (arg1), [arg2] "r" (arg2)
        /* 逐行：第三个冒号列破坏项：告知编译器汇编可能访问内存；它不代表执行了硬件 fence。 */
        : "memory"
    /* 逐行：结束这条内联汇编语句，继续执行 C 控制流；汇编文本与操作数描述共同构成一条语句。 */
    );
    /* 逐行：把从 a0 取得并写入 C 变量的结果返回给专用服务包装函数。 */
    return ret_val;
/* 逐行：结束当前函数、分支或循环的作用域；右花括号本身不执行输出或修改数据。 */
}

/*
 * sbi_console_putchar：调用编号为 1 的旧式 SBI 控制台输出服务。
 * 参数 ch：要输出的字节；返回值：无，忽略 sbi_call 的返回值。
 * 字符放在第一个参数中，另外两个参数置零。真正的设备输出由固件完成。
 */
/* 逐行：进入字符输出专用包装，参数为单个无符号字节，函数不返回服务结果。 */
void sbi_console_putchar(unsigned char ch) {
    /* 逐行：选择编号 1，以 ch 作为 arg0，另外两个参数置零；忽略通用调用返回值。 */
    sbi_call(SBI_CONSOLE_PUTCHAR, ch, 0, 0);
/* 逐行：结束当前函数、分支或循环的作用域；右花括号本身不执行输出或修改数据。 */
}

/*
 * sbi_set_timer：调用编号为 0 的旧式 SBI 定时器服务。
 * 参数 stime_value：下一次定时器事件的绝对计时值，使用平台计时单位。
 * RV64 下通过 a0 传递 64 位值；其余参数为零。返回值：无。
 * 本函数只请求设置定时器，Lab1 没有调用它，也没有建立定时中断处理流程。
 */
/* 逐行：进入设置定时器包装，传入绝对计时值；Lab1 当前不调用它。 */
void sbi_set_timer(unsigned long long stime_value) {
    /* 逐行：选择编号 0；在 RV64 下通过 a0 传入完整计时值，a1/a2 为零。 */
    sbi_call(SBI_SET_TIMER, stime_value, 0, 0);
/* 逐行：结束当前函数、分支或循环的作用域；右花括号本身不执行输出或修改数据。 */
}
